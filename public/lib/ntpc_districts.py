#: 全部行政區名（供 UI 下拉選單使用；照習慣的區序排列＝上方 dict 的插入序）。
DISTRICT_NAMES: list[str] = list(NTPC_DISTRICTS.keys())


def find_district_in_text(address: str) -> str | None:
    """在地址字串中尋找新北市行政區名；找到回傳區名，否則 None。

    比對時容許「板橋」與「板橋區」兩種寫法（去掉「區」字亦可命中）。
    以最長區名優先，避免「三」「板」等單字誤判。
    """
    if not address:
        return None
    text = address.strip()
    # 以完整區名（含「區」）優先，再退而比對去「區」的短名。
    for name in sorted(NTPC_DISTRICTS, key=len, reverse=True):
        if name in text:
            return name
    for name in sorted(NTPC_DISTRICTS, key=len, reverse=True):
        short = name[:-1] if name.endswith("區") else name
        if short and short in text:
            return name
    return None


def district_center(name: str) -> tuple[float, float] | None:
    """回傳某行政區的中心座標；未知區名回傳 None。"""
    return NTPC_DISTRICTS.get(name)
